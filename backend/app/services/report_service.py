"""
Report export (CSV and PDF) into storage/reports/.

File names are generated by the server (<type>_<timestamp>_<id>.<ext>) and looked up by
report id, so a download request can never point at an arbitrary file on disk.
"""

from __future__ import annotations

import io
from datetime import datetime, timezone
from typing import Any

import pandas as pd
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from app.schemas.models import StoredRecords
from app.services import analytics_service, forecast_service, inventory_service, model_service
from app.services.storage_service import append_json_record, load_json, lock_for, new_record_id, storage_path
from app.utils.errors import AppError, NotFoundError
from ml.utils import atomic_write_text

INDEX = ("reports", "reports_index.json")


# --------------------------------------------------------------------------- data builders
def _sales_tables() -> dict[str, pd.DataFrame]:
    k = analytics_service.kpis()
    kpi = pd.DataFrame([
        ("Gross fulfilled revenue (GBP)", f"{k['total_revenue']:,.2f}"), ("Units sold", f"{k['total_quantity']:,}"),
        ("Orders", f"{k['total_transactions']:,}"), ("Average order value (GBP)", f"{k['average_order_value']:,.2f}"),
        ("Products", f"{k['total_products']:,}"), ("Customers", f"{k['total_customers']:,}"),
        ("Period", f"{str(k['first_date'])[:10]} to {str(k['last_date'])[:10]}")], columns=["Metric", "Value"])
    monthly = pd.DataFrame(analytics_service.time_series("M"))
    monthly["period"] = pd.to_datetime(monthly["period"]).dt.strftime("%Y-%m")
    top = pd.DataFrame(analytics_service.top_products("revenue", 15))[["StockCode", "Description", "quantity", "revenue", "revenue_share_pct"]]
    products = pd.DataFrame(analytics_service.catalog()["products"])
    return {"Key figures (dataset-derived)": kpi,
            "Monthly sales": monthly[["period", "revenue", "quantity", "transactions", "customers", "is_partial"]],
            "Top 15 products by revenue": top, "_csv": products}


def _forecast_tables() -> dict[str, pd.DataFrame]:
    hist = pd.DataFrame(forecast_service.history(None, 1000))
    perf = model_service.performance()
    comp = pd.DataFrame(perf["comparison"])
    comp = comp[comp["split"] == "test"][["model", "mae", "rmse", "wape_pct", "mape_pct", "r2", "bias"]].round(3)
    rows = []
    for r in hist.head(200).to_dict(orient="records") if not hist.empty else []:
        try:
            rec = forecast_service.record(r["record_id"])
        except NotFoundError:
            continue
        rows += [{"record_id": r["record_id"], "stock_code": rec["stock_code"], "horizon_days": rec["horizon_days"],
                  "date": d["date"][:10], "predicted_demand": d["predicted_demand"], "is_open": d["is_open"]} for d in rec["daily"]]
    daily = pd.DataFrame(rows)
    return {"Model performance on the test period (calculated)": comp,
            "Saved forecasts (model-predicted)": hist[["created_at", "stock_code", "description", "horizon_days",
                                                        "total_forecast_units", "average_daily_demand"]] if not hist.empty else hist,
            "_csv": daily if not daily.empty else hist}


def _inventory_tables() -> dict[str, pd.DataFrame]:
    recs = inventory_service.recommendations(None, 10000)
    df = pd.DataFrame([{
        "created_at": r["created_at"], "stock_code": r["stock_code"], "description": r.get("description"),
        "current_stock": r["inputs"]["current_stock"], "lead_time_days": r["inputs"]["lead_time_days"],
        "service_level": r["inputs"]["service_level"], "avg_daily_demand": r["average_daily_demand"],
        "safety_stock": r["safety_stock"], "reorder_point": r["reorder_point"], "target_stock": r["target_stock"],
        "suggested_order_qty": r["suggested_order_quantity"], "status": r["status"]} for r in recs])
    risk = inventory_service.risk_summary()
    counts = pd.DataFrame(list(risk["status_counts"].items()), columns=["Status", "Products"])
    return {"Status of latest recommendation per product": counts,
            "Saved recommendations (user-entered inputs + calculated outputs)": df, "_csv": df}


BUILDERS = {"sales": _sales_tables, "forecast": _forecast_tables, "inventory": _inventory_tables}
TITLES = {"sales": "Sales Report", "forecast": "Demand Forecasting Report", "inventory": "Inventory Recommendations Report"}


# --------------------------------------------------------------------------- writers
def _pdf_bytes(report_type: str, tables: dict[str, pd.DataFrame]) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=landscape(A4), leftMargin=1.5 * cm, rightMargin=1.5 * cm,
                            topMargin=1.5 * cm, bottomMargin=1.5 * cm, title=TITLES[report_type])
    styles = getSampleStyleSheet()
    story: list[Any] = [Paragraph(f"AI Sales Forecasting &amp; Inventory Optimization — {TITLES[report_type]}", styles["Title"]),
                        Paragraph(f"Generated {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC. Source data: UCI Online Retail "
                                  "(Dec 2010 – Dec 2011). Inventory inputs are user-entered; forecasts are model-predicted.",
                                  styles["Normal"]), Spacer(1, 0.4 * cm)]
    for title, df in tables.items():
        if title.startswith("_"):
            continue
        story.append(Paragraph(title, styles["Heading2"]))
        if df is None or df.empty:
            story.append(Paragraph("No records yet.", styles["Normal"]))
            continue
        show = df.head(40).copy()
        for c in show.columns:
            if show[c].dtype == object:
                show[c] = show[c].astype(str).str.slice(0, 40)
        data = [list(map(str, show.columns))] + [[("" if pd.isna(v) else (f"{v:,.2f}" if isinstance(v, float) else str(v)))
                                                  for v in row] for row in show.itertuples(index=False)]
        t = Table(data, repeatRows=1)
        t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1E3A8A")),
                               ("TEXTCOLOR", (0, 0), (-1, 0), colors.white), ("FONTSIZE", (0, 0), (-1, -1), 7.5),
                               ("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
                               ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F1F5F9")])]))
        story += [t, Spacer(1, 0.4 * cm)]
        if len(df) > 40:
            story.append(Paragraph(f"Showing 40 of {len(df):,} rows; export CSV for all rows.", styles["Italic"]))
    doc.build(story)
    return buf.getvalue()


def generate(report_type: str, fmt: str) -> dict[str, Any]:
    if report_type not in BUILDERS:
        raise AppError(400, "INVALID_REPORT_TYPE", "report_type must be sales, forecast or inventory")
    tables = BUILDERS[report_type]()
    rid = new_record_id()
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
    file_name = f"{report_type}_report_{stamp}_{rid[:8]}.{fmt}"
    path = storage_path("reports", file_name)
    path.parent.mkdir(parents=True, exist_ok=True)
    if fmt == "csv":
        df = tables["_csv"]
        atomic_write_text(path, df.to_csv(index=False))
        rows = int(len(df))
    else:
        content = _pdf_bytes(report_type, tables)
        tmp = path.with_suffix(".tmp")
        with lock_for(path):
            tmp.write_bytes(content)
            tmp.replace(path)
        rows = None
    rec = append_json_record(storage_path(*INDEX), {
        "report_id": rid, "report_type": report_type, "format": fmt, "file_name": file_name,
        "size_bytes": path.stat().st_size, "rows": rows}, StoredRecords)
    return _info(rec)


def _info(rec: dict[str, Any]) -> dict[str, Any]:
    return {k: rec.get(k) for k in ("report_id", "report_type", "format", "file_name", "created_at", "size_bytes", "rows")} | \
        {"download_url": f"/api/reports/{rec['report_id']}/download"}


def list_reports() -> list[dict[str, Any]]:
    recs = load_json(storage_path(*INDEX), lambda: {"records": []}, StoredRecords)["records"]
    return [_info(r) for r in reversed(recs) if storage_path("reports", r["file_name"]).exists()]


def file_for(report_id: str):
    for r in load_json(storage_path(*INDEX), lambda: {"records": []}, StoredRecords)["records"]:
        if r.get("report_id") == report_id:
            path = storage_path("reports", r["file_name"])
            if path.exists():
                return path, r["file_name"], "application/pdf" if r["format"] == "pdf" else "text/csv"
    raise NotFoundError("Report not found.")
